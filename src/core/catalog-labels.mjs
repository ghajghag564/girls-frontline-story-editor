const columns = {'zh-TW': 0, en: 1, ja: 2};

export function catalogCharacterNames(character, language) {
  const labels = Object.hasOwn(columns, language) ? character.displayNames?.[language] : undefined;
  return {name: labels?.name || character.name, styleName: labels?.styleName || character.styleName};
}

export function catalogCharacterSearchText(character) {
  const translations = Object.keys(columns).flatMap(language => {
    const labels = character.displayNames?.[language];
    return [labels?.name, labels?.styleName];
  });
  return [character.name, character.styleName, character.id, character.resourceId, character.sourceName,
    ...(character.aliases ?? []), ...translations].filter(Boolean).join(" ").normalize("NFKC").toLowerCase();
}

export function catalogExpressionName(expression, language) {
  const name = expression.name || expression.id;
  if (!Object.hasOwn(columns, language)) return name;
  const variant = /^(.*?)((?: · \d+)+)?$/.exec(name);
  if (!variant) return name;
  const [, label, suffix = ""] = variant;
  const translated = expressionLabels.get(label)?.[columns[language]];
  if (translated) return translated + suffix;
  const numbered = /^表情 (\d+)$/.exec(label);
  if (numbered && language === "en") return "Expression " + numbered[1] + suffix;
  return name;
}
